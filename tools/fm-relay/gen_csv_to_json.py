def 書く(画面, 前列, 行たち, 元見出し, 鍵列, 作る):
    """前列: Excel 書き出しと同じ列名（先頭）。そのあと CSV の全列（前列と重ならないもの）"""
    見出し = list(前列) + [h for h in 元見出し if h and h not in 前列]
    out = []
    for r in 行たち:
        head = 作る(r)
        row = [head.get(h, r.get(h, '')) for h in 見出し]
        out.append(row)
    p = os.path.join(DST, 'GEN取込_' + 画面 + '.json')
    json.dump({'画面': 画面, '見出し': 見出し, '鍵列': 鍵列, '行': out}, open(p, 'w', encoding='utf-8'), ensure_ascii=False)
    print('%s: %d 行 × %d 列 → %s (%.1f MB)' % (画面, len(out), len(見出し), os.path.basename(p), os.path.getsize(p) / 1e6))


