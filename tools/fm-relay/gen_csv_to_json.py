def 読む(画面):
    for name in FILES[画面]:
        p = os.path.join(SRC, name)
        if os.path.exists(p):
            rows = list(csv.reader(io.StringIO(open(p, 'rb').read().decode('cp932', errors='replace'))))
            見出し = [掃除(h) for h in rows[0]]
            return 見出し, [dict(zip(見出し, r)) for r in rows[1:] if any(c.strip() for c in r)], name
    return None, [], None


def 掃除(h):
    """CSV の長い見出しを Hub で使う短い名前に"""
    h = h.strip()
    h = re.sub(r'\s*\*\s*$', '', h)                       # 「ロット区分 *」の *
    h = re.sub(r'\(この項目の値はインポートされない.*$', '', h)  # 行(この項目…)、製番(この項目…)
    h = re.sub(r'\(0:なし、1:現金.*$', '', h)              # 入金種別(0:なし…)
    h = re.sub(r'（「1」:yes、それ以外: no）', '', h)
    h = re.sub(r'\((?:0|round)[^)]*$', '', h)             # 管理区分(0:製番…) の切れた説明
    return h.strip()


def 数(v):
    """'100.0000000000' → '100'、'6000' → '6000'、'' → ''"""
    s = str(v or '').strip()
    if not s:
        return ''
    try:
        f = float(s)
        return str(int(f)) if f == int(f) else ('%g' % f)
    except ValueError:
        return s


def 掛ける(a, b):
    try:
        f = float(a or 0) * float(b or 0)
        return str(int(f)) if f == int(f) else ('%g' % f)
    except ValueError:
        return ''


def 受注番号_(製番):
    return re.sub(r'-\d+$', '', str(製番 or '').strip())


