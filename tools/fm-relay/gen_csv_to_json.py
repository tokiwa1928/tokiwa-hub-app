# ------------------------------------------------------------ 入金・支払（行番号は同じ番号の並び順で振る。GEN の CSV に「行」が無いため）
def 行を振る(rows, 番号列):
    # 同じ番号の何行目か（ファイル内で離れていても数える）
    n = {}
    for r in rows:
        n[r[番号列]] = n.get(r[番号列], 0) + 1
        r['行'] = str(n[r[番号列]])


